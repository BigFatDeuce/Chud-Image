export type Lang = "fr" | "en";
const dictionaries: Record<Lang, Record<Key, string>> = { fr, en };

export function resolveLang(setting: LanguageSetting): Lang {
  if (setting === "fr" || setting === "en") return setting;
  const nav = typeof navigator !== "undefined" ? navigator.language : "en";
  return nav.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function makeTranslator(lang: Lang): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => {
    let text = dict[key] ?? fr[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
    return text;
  };
}

export interface I18n {
  lang: Lang;
  t: Translate;
}

export const I18nContext = createContext<I18n>({ lang: "fr", t: makeTranslator("fr") });
export const useI18n = () => useContext(I18nContext);
